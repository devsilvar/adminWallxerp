/**
 * Withdrawal Failed / Rejected Email Template
 *
 * Sent when a merchant payout fails at the banking gateway or is declined by an administrator.
 * Confirms that reserved funds have been unlocked and returned to the merchant's available wallet balance.
 */

export interface WithdrawalFailedEmailData {
  ownerName: string;
  businessName: string;
  amountFormatted: string;
  destinationBankName: string;
  accountNumberMasked: string;
  transferReference: string;
  failureReason: string;
  isRejection: boolean;
  failedDate: string;
  payoutSettingsLink: string;
}

