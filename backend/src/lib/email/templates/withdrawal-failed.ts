export function generateWithdrawalFailedText(data: WithdrawalFailedEmailData): string {
  const subtitle = data.isRejection ? 'WITHDRAWAL DECLINED' : 'WITHDRAWAL UNSUCCESSFUL';
  return `
WALLX ERP - ${subtitle}
==================================================

Hello ${data.ownerName},

Your withdrawal of ${data.amountFormatted} from ${data.businessName} could not be completed. The full reserved amount has been restored to your available wallet balance.

DETAILS:
- Amount Restored: ${data.amountFormatted}
- Destination Bank: ${data.destinationBankName} (${data.accountNumberMasked})
- Reference: ${data.transferReference}
- Reason: ${data.failureReason}
- Date: ${data.failedDate}

Review your wallet & retry:
${data.payoutSettingsLink}

---
WallX ERP • Nigeria SME Business Management & Tax Compliance
support@wallxerp.com
  `.trim();
}
